"""
Generate country-data.js (the apply page's country picker data) from
backend/services/countries.py, the single source of truth.

    python tools/build_country_picker.py          # rewrite country-data.js
    python tools/build_country_picker.py --check  # exit 1 if it is out of date

Run python bump_versions.py afterwards so pages pick up the new file.
Flags live in assets/flags/<iso>.png (40px) and <iso>@2x.png (80px), from flagcdn.com.
"""
import json
import os
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "backend"))
from services.countries import ALIASES, COUNTRIES, EXTRA_PREFIXES, PRIMARY_FOR_DIAL  # noqa: E402

OUT = os.path.join(ROOT, "country-data.js")


def _fold(name: str) -> str:
    return unicodedata.normalize("NFD", name).encode("ascii", "ignore").decode().lower()


def render() -> str:
    rows = []
    for iso, name, dial in sorted(COUNTRIES, key=lambda c: _fold(c[1])):
        row = [iso, name, dial]
        if iso in ALIASES:
            row.append(ALIASES[iso])
        rows.append(json.dumps(row, ensure_ascii=False))
    return (
        "/* Generated by tools/build_country_picker.py from backend/services/countries.py. Do not edit. */\n"
        "window.SKILLME_COUNTRIES = {\n"
        "  // [iso2, name, dial code without '+', search aliases?]\n"
        "  list: [\n    " + ",\n    ".join(rows) + "\n  ],\n"
        "  primary: " + json.dumps(PRIMARY_FOR_DIAL) + ",\n"
        "  prefixes: " + json.dumps(EXTRA_PREFIXES, separators=(",", ":")) + "\n"
        "};\n"
    )


def main():
    text = render()
    current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if "--check" in sys.argv:
        if current != text:
            print("country-data.js is out of date: run python tools/build_country_picker.py")
            sys.exit(1)
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"Wrote {OUT} ({len(COUNTRIES)} countries)")


if __name__ == "__main__":
    main()
